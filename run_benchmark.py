import logging
from energy_orchestrator import EnergyOrchestrator
from benchmark_runner import BenchmarkRunner
from utils import setup_logging, MemoryManager, Dataset
from metrics_visualizer import plot_latency, plot_memory, plot_rating_distribution
import pandas as pd
import random

if __name__ == '__main__':
    config = {
        "benchmark": {
            "iterations": 3,
            "total_questions": 5
        },
        "model": {
            "max_calls": 4,
            "pause_time": 30,
            "token_limit": 90000
        },
        "data": {
            "paths": {
                "input_dir": "data/questions",
                "metrics": "output/metrics"
            }
        }
    }

    logger = setup_logging()
    orchestrator = EnergyOrchestrator()
    runner = BenchmarkRunner("CrewAI_Energy", orchestrator, config, logger)
    dataset = Dataset(
        data_dir=config["data"]["paths"]["input_dir"],
        total_questions=config["benchmark"]["total_questions"]
    )

    benchmark = runner.run_benchmark(config["benchmark"]["iterations"], dataset)

    df = pd.DataFrame([i.to_dict() for i in benchmark.iterations])
    df['simulated_rating'] = df['response_text'].apply(lambda text: random.uniform(3.5, 5))

    plot_latency(df)
    plot_memory(df)
    plot_rating_distribution(df)

    df.to_json("output/metrics/benchmark_results.jsonl", orient="records", lines=True)