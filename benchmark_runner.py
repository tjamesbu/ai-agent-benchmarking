from typing import Dict
from pathlib import Path
from rating_simulator import simulate_rating
import time
import numpy as np
from utils import MemoryManager, Dataset

class IterationMetrics:
    def __init__(self, iteration, runtime, memory_delta, peak_memory, llm_calls, avg_latency,
                 total_prompt_tokens, tokens_per_call, agent, response_text):
        self.iteration = iteration
        self.runtime = runtime
        self.memory_delta = memory_delta
        self.peak_memory = peak_memory
        self.llm_calls = llm_calls
        self.avg_latency = avg_latency
        self.total_prompt_tokens = total_prompt_tokens
        self.tokens_per_call = tokens_per_call
        self.agent = agent
        self.response_text = response_text

    def to_dict(self):
        return self.__dict__

class BenchmarkMetrics:
    def __init__(self, framework: str, config: Dict):
        self.framework = framework
        self.config = config
        self.iterations = []
        self.memory_delta = 0
        self.peak_memory = 0

class BenchmarkRunner:
    def __init__(self, benchmark_name: str, orchestrator, config: Dict, logger):
        self.benchmark_name = benchmark_name
        self.orchestrator = orchestrator
        self.config = config
        self.logger = logger

    def run_iteration(self, iteration: int, dataset: Dataset, memory_manager: MemoryManager):
        start_time = time.time()
        peak_memory = 0

        questions = dataset.get_questions()

        latencies = []
        total_prompt_tokens = 0
        total_tokens = 0
        llm_calls = 0

        for question in questions:
            try:
                result = self.orchestrator.run(question["question"])

                latencies.append(result['latency'])
                total_prompt_tokens += result['prompt_tokens']
                total_tokens += result['total_tokens']
                llm_calls += (result['retry_count'] + 1)

                current_stats = memory_manager.get_memory_stats()
                peak_memory = max(peak_memory, current_stats['current'])

                self.logger.info(f"\tAgent: {result['agent']}, Latency: {result['latency']:.2f}s")

            except Exception as e:
                self.logger.error(f"Prediction failed: {str(e)}")
                continue

        end_stats = memory_manager.get_memory_stats()

        return IterationMetrics(
            iteration=iteration+1,
            runtime=time.time() - start_time,
            memory_delta=end_stats['delta'],
            peak_memory=peak_memory,
            llm_calls=llm_calls,
            avg_latency=np.mean(latencies) if latencies else 0.0,
            total_prompt_tokens=total_prompt_tokens,
            tokens_per_call=total_tokens / llm_calls if llm_calls > 0 else 0.0,
            agent=result['agent'],
            response_text=result['predicted_yield']
        )

    def run_benchmark(self, iterations: int, dataset: Dataset) -> BenchmarkMetrics:
        benchmark = BenchmarkMetrics(framework=self.benchmark_name, config=self.config)
        memory_manager = MemoryManager()
        memory_manager.start = memory_manager.process.memory_info().rss / (1024 * 1024)

        for iteration in range(iterations):
            self.logger.info(f"Starting iteration {iteration + 1}/{iterations}")
            if iteration > 0:
                memory_manager.reset_tracking()
            result = self.run_iteration(iteration, dataset, memory_manager)
            benchmark.iterations.append(result)

        final_stats = memory_manager.get_memory_stats()
        benchmark.memory_delta = final_stats['delta']
        benchmark.peak_memory = final_stats['overall_peak']
        return benchmark