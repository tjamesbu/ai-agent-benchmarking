import plotly.express as px
import pandas as pd

def plot_latency(df: pd.DataFrame):
    fig = px.line(df, x='iteration', y='avg_latency', title='Average Latency per Iteration')
    fig.show()

def plot_memory(df: pd.DataFrame):
    fig = px.line(df, x='iteration', y='peak_memory', title='Peak Memory per Iteration (MB)')
    fig.show()

def plot_rating_distribution(df: pd.DataFrame):
    fig = px.histogram(df, x='simulated_rating', nbins=10, title='Simulated Rating Distribution')
    fig.show()