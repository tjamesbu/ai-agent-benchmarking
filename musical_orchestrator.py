from orchestrator_base import OrchestratorBase
from advisor_agents import Night_Life_Advisor
import time

class MusicalOrchestrator(OrchestratorBase):
    def __init__(self):
        advisor = Night_Life_Advisor()
        self.agent = advisor.musical_genre_and_culture()

    def run(self, question: str):
        start_time = time.time()

        try:
            result = self.agent.run(question)
        except Exception as e:
            return {
                'predicted_yield': None,
                'agent': 'Musical Genre & Culture Advisor',
                'latency': time.time() - start_time,
                'prompt_tokens': 0,
                'total_tokens': 0,
                'retry_count': 0,
                'error': str(e)
            }

        prompt_tokens = len(question.split())
        output_tokens = len(result.split())

        return {
            'predicted_yield': result,
            'agent': 'Musical Genre & Culture Advisor',
            'latency': time.time() - start_time,
            'prompt_tokens': prompt_tokens,
            'total_tokens': prompt_tokens + output_tokens,
            'retry_count': 0
        }